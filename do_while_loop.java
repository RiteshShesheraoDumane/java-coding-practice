import java.util.Scanner;

public class do_while_loop {
public static void main(String[] args) {
	Scanner sc=new Scanner(System.in);
	System.out.println("enter any number:");
	int num=sc.nextInt();
	do {
		System.out.println("learn coding");
		num++;
		
	}
	while(num<=10);
			
			
}
}
